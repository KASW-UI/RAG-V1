#!/usr/bin/env bash
# ============================================================================
# favorite 域**场景轮**的变异验证 —— 证明「场景轮的判据有牙齿」，不是恒绿。
# ----------------------------------------------------------------------------
# 🔴 **两轮变异**（每轮都是「只动 C 侧」⇒ 才能证明判据真的在**比两侧**）：
#
#   ① **S2 并发**：删掉唯一索引 `uk_user_folder_name`
#      ⇒ ⇒ 并发建同名收藏夹时**不再有唯一键兜底**
#      ⇒ ⇒ 「先查重后插入」的竞态暴露 ⇒ ⇒ 8 个同名请求**全部成功**。
#      ⇒ ⇒ S2 的「分布 = 200:1,5203:7」断言必须红。
#
#   ② **S6 幂等重放**：把 C 侧 folder 9002 的名字改成 'BetaMutated'
#      ⇒ ⇒ 「改成**当前名字**」这条路径**不再命中「同名 ⇒ 直接成功不写库」的早退**
#      ⇒ ⇒ 第一次改名就**真的写库** ⇒ ⇒ `update_time` 被推进
#      ⇒ ⇒ S6 的「同名改名**不写库**（update_time 不动）」断言必须红。
#      ⇒ 🔴 **为什么挑这个点**：它是**唯一**「业务码不变、只有副作用变」的断言
#      ⇒ ⇒ 六个业务码断言**照旧全绿** ⇒ ⇒ 只有「update_time 不动」这条能抓住它
#      ⇒ ⇒ ⇒ 正好证明**那条断言不是恒真**（它在测「有没有写库」，不是「码对不对」）。
#
# 为什么挑①这个点：
#   · 它是 **L2 业务语义**（重名保护）—— DDL 里那条唯一索引的注释写得很清楚：
#     「删掉这个约束 ⇒ 并发下两个同名收藏夹都能建出来，重名保护失效」；
#   · 单测**很难**抓到（要同时发起 8 个并发请求并断言「恰好 1 个成功」）；
#   · 🔴 但场景轮的 S2 断言**直接**问「成功了几个 / 库里留了几行」⇒ ⇒ **必然被抓到**。
#
# 🔴 **为什么只动一侧**：
#   若两侧同时坏 ⇒ 场景轮只能证明「两侧相等」⇒ 证不了「它在比两侧」。
#   ⇒ ⇒ 只动 C 侧 ⇒ 判据必须靠「两侧不等」抓出来 ⇒ ⇒ **才证明判据真的在比两侧**。
#
# 判定（每轮两次跑）：
#   ① 变异后跑 ⇒ **必须红**（EXIT=1）且**必须**命中该轮的 C 侧断言标识；
#   ② 不带变异再跑 ⇒ **必须绿**（EXIT=0）**且必须**看到该轮的「绿色」标识
#      ⇒ ⇒ 后者防的是「判据根本没跑到」这种假绿。
#   ⇒ ⇒ 「红→绿」证明：① 判据确实在检测那个行为；② 变异确实没留下（DB 每次跑现建 ⇒ 净改动 = 0）。
#
# ⚠️ **变异是 DB 级的**（不碰任何源文件）⇒ ⇒ 没有「还原」动作可做 ⇒ ⇒ **净改动天然 = 0**
#    （容器每次现建现删 ⇒ 下一轮跑的是干净库）。
#
# 用法：bash tools/difftest/favorite/mutate-scenarios.sh
# ============================================================================
set -uo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"

say() { printf '\033[1;36m[mutate-scenarios/favorite]\033[0m %s\n' "$*"; }
ok()  { printf '\033[1;32m  ✅ %s\033[0m\n' "$*"; }
bad() { printf '\033[1;31m  ❌ %s\033[0m\n' "$*"; }
die() { bad "$*"; exit 2; }

# 变异轮的日志放临时目录 ⇒ 不污染仓内
MUT_LOG="$(mktemp)"
trap 'rm -f "${MUT_LOG}"' EXIT

# ── 变异表的一次执行 ────────────────────────────────────────────────────
# 🔴 变异 SQL：**只**作用在 C 侧的库（fav_c_db）⇒ run.sh 的变异钩子只对 C 侧执行
#
# $1 label            变异说明
# $2 mutation_sql     变异 SQL
# $3 expect_red       变异后**必须**命中的 C 侧断言标识（红）
# $4 expect_green     不带变异后**必须**看到的 C 侧断言标识（绿）
# $5 b_must_not_red   **不得**出现的 B 侧断言标识（出现 ⇒ 变异波及了 B 侧 ⇒ 证据不可信）
run_mutation() {
  local label="$1" mutation="$2" expect_red="$3" expect_green="$4" b_must_not_red="$5"

  say "变异（仅 C 侧 · ${label}）：${mutation}"

  # ⚠️ ONLY_SCENARIOS=1 ⇒ 只跑场景轮 ⇒ 矩阵与 gRPC 面**不参与**
  #    ⇒ 变异若让矩阵先红 ⇒ 红的就不是被验的那一面 ⇒ 证据不可信。
  ONLY_SCENARIOS=1 SCENARIO_MUTATION="${mutation}" bash "${HERE}/run.sh" > "${MUT_LOG}" 2>&1
  local red_rc=$?

  if [ "${red_rc}" -ne 1 ]; then
    bad "变异后场景轮 **没有红**（exit=${red_rc}）⇒ 判据可能恒绿 ⇒ 场景轮无效"
    tail -40 "${MUT_LOG}"
    exit 1
  fi
  if ! grep -q "${expect_red}" "${MUT_LOG}"; then
    bad "变异后红了，但**没有**命中「${expect_red}」⇒ 红的可能是别的原因 ⇒ 不可信"
    tail -40 "${MUT_LOG}"
    exit 1
  fi
  ok "变异后：EXIT=1 且命中「${expect_red}」⇒ 判据确实在检测那个行为"

  # 🔴 额外确认：红的**必须**只出现在 C 侧 ⇒ （B 侧未被变异 ⇒ B 侧断言必须仍然是绿的）
  if grep -q "${b_must_not_red}" "${MUT_LOG}"; then
    bad "变异后 **B 侧**也红了 ⇒ 变异波及了没被改的那一侧 ⇒ 证据不可信"
    tail -40 "${MUT_LOG}"
    exit 1
  fi
  ok "变异只波及 C 侧（B 侧断言未红）⇒ 判据确实在**比两侧**"

  # ── 不带变异再跑（期望：绿）───────────────────────────────────────────
  say "不带变异再跑场景轮（期望：绿）"
  ONLY_SCENARIOS=1 bash "${HERE}/run.sh" > "${MUT_LOG}" 2>&1
  local green_rc=$?
  if [ "${green_rc}" -ne 0 ]; then
    bad "不带变异时场景轮仍然红（exit=${green_rc}）⇒ 判据本身有问题（不是恒绿 ⇒ 是恒红）"
    tail -40 "${MUT_LOG}"
    exit 1
  fi
  # 🔴 防「判据根本没跑到」：必须**看到**该轮那条绿色断言 ⇒ ⇒ 否则「绿」是空绿
  if ! grep -q "${expect_green}" "${MUT_LOG}"; then
    bad "不带变异时没看到「${expect_green}」⇒ 判据**没跑到**那个断言 ⇒ 假绿"
    tail -40 "${MUT_LOG}"
    exit 1
  fi
  ok "不带变异：EXIT=0 且看到「${expect_green}」⇒ 判据绿 ⇒ 净改动 = 0（DB 每次现建）"
}

# ── ① S2 并发 ───────────────────────────────────────────────────────────
run_mutation \
  "S2 并发 · 删唯一索引" \
  "DROP INDEX IF EXISTS uk_user_folder_name" \
  "S2 C 侧并发结果分布" \
  "两侧并发结果分布相同" \
  "S2 B 侧并发结果分布 ="

# ── ② S6 幂等重放 ───────────────────────────────────────────────────────
run_mutation \
  "S6 幂等 · 改掉 9002 的名字（让同名早退不命中）" \
  "UPDATE favorite_folder SET name='BetaMutated' WHERE folder_id=9002" \
  "S6 C 侧 folder 9002 的 update_time 被推进了" \
  "C 侧 folder 9002 的 update_time 未推进" \
  "S6 B 侧 folder 9002 的 update_time 被推进了"

echo
ok "场景轮变异验证通过（两轮红 → 绿）⇒ 判据有牙齿"
exit 0
